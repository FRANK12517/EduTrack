'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const root = path.resolve(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
assert.strictEqual(pkg.engines.node, '22.x');
const vercel = JSON.parse(fs.readFileSync(path.join(root, 'vercel.json'), 'utf8'));
assert.ok(vercel.rewrites.some((r) => r.source === '/api/:path*' && r.destination === '/api/index.js'));
const probe = spawnSync(process.execPath, ['-e', "require('./server')"], { cwd: root, env: { ...process.env, NODE_ENV: 'production', VERCEL: '1', EDUTRACK_DATABASE_URL: '', EDUTRACK_ALLOWED_ORIGINS: 'https://staging.invalid' }, encoding: 'utf8' });
assert.notStrictEqual(probe.status, 0);
assert.match(`${probe.stdout}\n${probe.stderr}`, /EDUTRACK_DATABASE_URL/);
assert.doesNotMatch(`${probe.stdout}\n${probe.stderr}`, /ENOENT.*\/var\/task\/data/);
console.log('Part 41 runtime repair checks passed.');
