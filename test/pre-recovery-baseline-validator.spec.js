'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { EXPECTED_TABLES, EXPECTED_APPLICATION_FOREIGN_KEYS, EXPECTED_DATABASE_FOREIGN_KEYS, REQUIRED_MIGRATIONS, FORBIDDEN_ENV, config, classify } = require('../scripts/validate-pre-recovery-baseline');
const authorized = { EDUTRACK_PRODUCTION_PREFLIGHT_TARGET: 'production-read-only', SUPABASE_DB_URL: 'postgresql://hidden:hidden@example.test:5432/postgres' };
assert.equal(config(authorized).ssl.rejectUnauthorized, true);
for (const key of FORBIDDEN_ENV) assert.throws(() => config({ ...authorized, [key]: 'forbidden' }), key);
assert.equal(EXPECTED_TABLES.length, 84);
assert.equal(EXPECTED_APPLICATION_FOREIGN_KEYS, 156);
const exact = { tableCount: EXPECTED_TABLES.length + 1, applicationTableCount: EXPECTED_TABLES.length, missingApplicationTables: [], unexpectedApplicationTables: [], requiredMigrations: REQUIRED_MIGRATIONS, appliedMigrations: REQUIRED_MIGRATIONS, schemaMigrationCount: 3, rowLevelSecurityTableCount: EXPECTED_TABLES.length, authIdentityMappingPresent: true, foreignKeyCount: EXPECTED_DATABASE_FOREIGN_KEYS };
assert.equal(classify(exact), 'SUPABASE_PRODUCTION_SCHEMA_READY');
assert.equal(classify({ ...exact, foreignKeyCount: EXPECTED_DATABASE_FOREIGN_KEYS - 1 }), 'SUPABASE_PRODUCTION_SCHEMA_INCOMPLETE');
assert.equal(classify({ ...exact, missingApplicationTables: ['students'] }), 'SUPABASE_PRODUCTION_SCHEMA_INCOMPLETE');
assert.equal(classify({ ...exact, appliedMigrations: REQUIRED_MIGRATIONS.slice(1) }), 'SUPABASE_PRODUCTION_SCHEMA_INCOMPLETE');
assert.equal(classify({ ...exact, rowLevelSecurityTableCount: EXPECTED_TABLES.length - 1 }), 'SUPABASE_PRODUCTION_SCHEMA_INCOMPLETE');
const workflow = fs.readFileSync('.github/workflows/validate-pre-recovery-baseline.yml', 'utf8');
assert.match(workflow, /workflow_dispatch/); assert.doesNotMatch(workflow, /pull_request|push:/);
assert.match(workflow, /secrets\.SUPABASE_DB_URL/);
assert.match(workflow, /secrets\.EDUTRACK_PRODUCTION_PREFLIGHT_TARGET/);
assert.doesNotMatch(workflow, /secrets\.(?:TIDB_|DATABASE_URL|EDUTRACK_TIDB_)/);
console.log('Supabase production baseline read-only guards passed.');
