'use strict';
const assert = require('node:assert/strict');
const { category } = require('../lib/postgres-connectivity-diagnostic');
assert.equal(category({ code: 'ENOTFOUND' }), 'ENDPOINT');
assert.equal(category({ code: 'ECONNREFUSED' }), 'NETWORK');
assert.equal(category({ code: 'ETIMEDOUT' }), 'NETWORK');
assert.equal(category({ code: '28P01' }), 'AUTHENTICATION');
assert.equal(category({ code: '3D000' }), 'DATABASE');
assert.equal(category({ code: 'HANDSHAKE_SSL_ERROR' }), 'TLS');
assert.equal(category({ code: '57P01' }), 'NETWORK');
assert.equal(category({ code: 'XX999' }), 'UNCLASSIFIED_XX999');
assert.equal(category({ code: 'unsafe value with host.example' }), 'UNKNOWN');
assert.equal(category({ code: 'unrecognized' }), 'UNKNOWN');
console.log('PostgreSQL connectivity diagnostic sanitization passed.');
